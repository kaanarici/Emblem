enum Hugeicons {
    static func asset(for symbol: String?) -> String? {
        guard var name = symbol?.trimmingCharacters(in: .whitespacesAndNewlines).lowercased(),
              !name.isEmpty, !filledSymbols.contains(name) else { return nil }
        name = strokeName(name)
        while true {
            if let hit = map[name] { return "Hugeicons/" + hit }
            if let dot = name.lastIndex(of: ".") {
                name = String(name[..<dot])
            } else {
                return nil
            }
        }
    }

    static let filledSymbols: Set<String> = ["clock.fill", "checkmark.circle.fill"]

    static func strokeName(_ symbol: String) -> String {
        var name = symbol
        while let range = name.range(of: ".fill") { name.removeSubrange(range) }
        return name
    }

    static func isRenderable(_ symbol: String?) -> Bool {
        guard let symbol, !symbol.isEmpty else { return false }
        return asset(for: symbol) != nil || UIImage(systemName: symbol) != nil
    }

