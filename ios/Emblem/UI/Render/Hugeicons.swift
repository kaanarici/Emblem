struct GlyphImage: View {
    let symbol: String
    var size: CGFloat
    var weight: Font.Weight = .medium

    var body: some View {
        if let asset = Hugeicons.asset(for: symbol) {
            Image(asset)
                .resizable()
                .renderingMode(.template)
                .interpolation(.high)
                .frame(width: size, height: size)
        } else {
            Image(systemName: !Hugeicons.filledSymbols.contains(symbol)
                && UIImage(systemName: Hugeicons.strokeName(symbol)) != nil ? Hugeicons.strokeName(symbol) : symbol)
                .font(.system(size: size * 0.82, weight: weight))
                .frame(width: size, height: size)
        }
    }
}
